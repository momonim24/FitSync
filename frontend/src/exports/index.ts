/**
 * Report export entry point. Loaded lazily (dynamic import) when the user
 * clicks Download PDF / Export Excel, so jsPDF and ExcelJS are not part of
 * the main bundle. Files are built in the browser from the report JSON the
 * page already received from the API — the same data, date range and
 * permissions as the report on screen; no token or credential is included.
 */
import type { AdminReport, MemberReport, TrainerReport } from '../api/types';
import {
  FITNESS_DEFINITIONS,
  adminFitnessMetrics,
  adminFitnessTables,
  memberFitnessMetrics,
  memberFitnessTables,
  trainerFitnessMetrics,
  trainerFitnessTables,
} from './fitness-model';
import { adminDocument, memberDocument, trainerDocument, type ExportContext, type ReportDocument } from './model';

export type AnyReport = MemberReport | TrainerReport | AdminReport;
export type ExportFormat = 'pdf' | 'xlsx';

/** Version 2.0 sections are appended after the original ones, which stay unchanged. */
function withFitness(doc: ReportDocument, extra: Pick<ReportDocument, 'metrics' | 'tables'>): ReportDocument {
  return { ...doc, metrics: [...doc.metrics, ...extra.metrics], tables: [...doc.tables, ...extra.tables], definitions: [...doc.definitions, ...FITNESS_DEFINITIONS] };
}

export function toDocument(report: AnyReport, ctx: ExportContext = {}, memberViewedByTrainer = false): ReportDocument {
  // `fitness` is absent only when talking to a Version 1 backend.
  if (report.reportType === 'member') {
    const doc = memberDocument(report, ctx, memberViewedByTrainer);
    return report.fitness ? withFitness(doc, { metrics: memberFitnessMetrics(report), tables: memberFitnessTables(report) }) : doc;
  }
  if (report.reportType === 'trainer') {
    const doc = trainerDocument(report, ctx);
    return report.fitness ? withFitness(doc, { metrics: trainerFitnessMetrics(report), tables: trainerFitnessTables(report) }) : doc;
  }
  const doc = adminDocument(report, ctx);
  return report.fitness ? withFitness(doc, { metrics: adminFitnessMetrics(report), tables: adminFitnessTables(report) }) : doc;
}

const MIME: Record<ExportFormat, string> = {
  pdf: 'application/pdf',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
};

export async function buildReportFile(
  report: AnyReport,
  format: ExportFormat,
  ctx: ExportContext = {},
  memberViewedByTrainer = false,
): Promise<{ data: ArrayBuffer; filename: string; mime: string }> {
  const doc = toDocument(report, ctx, memberViewedByTrainer);
  const data = format === 'pdf' ? (await import('./pdf')).buildPdf(doc) : await (await import('./xlsx')).buildXlsx(doc);
  return { data, filename: `${doc.fileBase}.${format}`, mime: MIME[format] };
}

/** Triggers a browser download for generated bytes. */
export function saveFile(data: ArrayBuffer, filename: string, mime: string): void {
  const url = URL.createObjectURL(new Blob([data], { type: mime }));
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}
